# frozen_string_literal: true

require "rbconfig"
require "stringio"
require "tmpdir"
require "qube_sync/workflow_types"

# The golden files are the fixture document rendered with drafts. After a deliberate change to
# the output, write them again with UPDATE_GOLDEN=1 bundle exec rspec spec/qube_sync/workflow_types_spec.rb.
RSpec.describe QubeSync::WorkflowTypes do
  fixtures = File.expand_path("../fixtures/workflow_types", __dir__)
  root = File.expand_path("../..", __dir__)
  let(:source) { "https://qubesync.com/api/v2/workflows/types" }

  let(:document) { JSON.parse(File.read(File.join(fixtures, "document.json"))) }

  # A client that answers workflow_types from a queue (a document, :not_modified, or an
  # exception to raise), recording the calls, and records start_run.
  let(:fake_client) do
    Class.new do
      attr_reader :calls, :answers, :runs

      def initialize
        @calls = []
        @answers = []
        @runs = []
      end

      def base_url
        "https://qubesync.com"
      end

      def workflow_types(include_drafts: false, etag: nil)
        @calls << {include_drafts: include_drafts, etag: etag}
        answer = @answers.shift
        raise answer if answer.is_a?(Exception) || (answer.is_a?(Class) && answer <= Exception)

        answer
      end

      def start_run(connection_id, workflow, input, reference:, webhook_url:, version: nil)
        @runs << {connection_id: connection_id, workflow: workflow, input: input, reference: reference,
                  webhook_url: webhook_url, version: version}
        {"id" => "run-1"}
      end
    end.new
  end

  def render(doc, **options)
    described_class.render(doc, source: "https://qubesync.com/api/v2/workflows/types", **options)
  end

  # Loads a rendered Ruby file into a fresh QubeWorkflows.
  def load_ruby(ruby)
    Object.send(:remove_const, :QubeWorkflows) if defined?(QubeWorkflows)
    Dir.mktmpdir do |dir|
      path = File.join(dir, "qube_workflows.rb")
      File.write(path, ruby)
      load path
    end
    QubeWorkflows
  end

  after { Object.send(:remove_const, :QubeWorkflows) if defined?(QubeWorkflows) }

  def workflow(input, key: "sample")
    {"digest" => "sha256:#{"c" * 64}", "operations_digest" => QubeSync::Operations::DIGEST, "workflows" => {
      key => {"name" => "Sample", "description" => "A sample.", "version" => 1, "draft" => false, "input" => input}
    }}
  end

  describe "the fixture" do
    it "renders the golden files" do
      files = render(document, drafts: true)
      ruby_path = File.join(fixtures, "qube_workflows.rb")
      rbs_path = File.join(fixtures, "qube_workflows.rbs")
      if ENV["UPDATE_GOLDEN"]
        File.write(ruby_path, files.ruby)
        File.write(rbs_path, files.rbs)
      end
      expect(files.ruby).to eq(File.read(ruby_path))
      expect(files.rbs).to eq(File.read(rbs_path))
    end

    it "gives byte-identical files for the same document, however its keys are ordered" do
      shuffled = JSON.parse(JSON.generate(document))
      shuffled["workflows"] = shuffled["workflows"].to_a.reverse.to_h
      shuffled["workflows"].each_value { |entry| entry["input"]["properties"] = entry["input"]["properties"].to_a.reverse.to_h }
      first = render(document, drafts: true)
      second = render(shuffled, drafts: true)
      expect([second.ruby, second.rbs]).to eq([first.ruby, first.rbs])
    end

    it "records the digest and the drafts flag where --check reads them back" do
      files = render(document, drafts: true)
      expect(described_class.header(files.ruby)).to eq(described_class::Header.new(digest: document["digest"], drafts: true))
      expect(described_class.header(files.rbs)).to eq(described_class.header(files.ruby))
      expect(files.ruby).to start_with("# Generated by `qube_sync workflows --drafts` from #{source}: don't edit.")
    end

    it "types the published workflows only, without drafts" do
      files = render(document)
      expect(files.ruby).not_to include("module Resolve")
      expect(files.ruby).to include("# drafts: false", "module AddTransaction", "module Upsert")
      expect(render(document, drafts: true).ruby).to include("module Resolve", "    VERSION = nil")
    end

    it "loads, and its frozen_string_literal comment counts" do
      load_ruby(render(document, drafts: true).ruby)
      expect(QubeWorkflows.add_transaction).to eq(QubeWorkflows::AddTransaction)
      expect(QubeWorkflows::AddTransaction::WORKFLOW).to eq("add_transaction")
      expect(QubeWorkflows::AddTransaction::VERSION).to eq(3)
      expect(QubeWorkflows::AddTransaction::WORKFLOW).to be_frozen
    end

    it "validates with rbs against the gem's own signatures" do
      Dir.mktmpdir do |dir|
        File.write(File.join(dir, "qube_workflows.rbs"), render(document, drafts: true).rbs)
        rbs = Gem.bin_path("rbs", "rbs")
        output = IO.popen([RbConfig.ruby, rbs, "-I", File.join(root, "sig"), "-I", dir, "validate"],
          err: [:child, :out], &:read)
        expect($?.success?).to be(true), output
      end
    end

    it "warns when the served operations aren't the gem's" do
      expect(render(document).warnings.first).to include("aren't the ones qube_sync #{QubeSync::VERSION} was generated from")
      expect(render(document.merge("operations_digest" => QubeSync::Operations::DIGEST)).warnings).to eq([])
    end
  end

  # The document QuBe Sync served for the shipped templates (qube's GET /api/v2/workflows/types,
  # 2026-10-25): too big for golden files, so it's rendered, loaded and validated.
  describe "a served document" do
    let(:served) { JSON.parse(File.read(File.join(fixtures, "served.json"))) }

    it "renders, loads and validates with rbs, without warnings" do
      files = render(served)
      expect(files.warnings).to eq([])
      load_ruby(files.ruby)
      expect(QubeWorkflows.constants.size).to eq(served["workflows"].size)
      Dir.mktmpdir do |dir|
        File.write(File.join(dir, "qube_workflows.rbs"), files.rbs)
        output = IO.popen([RbConfig.ruby, Gem.bin_path("rbs", "rbs"), "-I", File.join(root, "sig"), "-I", dir, "validate"],
          err: [:child, :out], &:read)
        expect($?.success?).to be(true), output
      end
    end

    it "gives every branch of a workflow the same shape: the body positional in all of them or in none" do
      served["workflows"].each do |key, entry|
        workflow = described_class::Workflow.new(key, entry)
        expect(workflow.branches.map { |branch| branch.body&.name }.uniq.size).to be <= 1, key
      end
    end
  end

  describe "the generated methods" do
    before do
      load_ruby(render(document, drafts: true).ruby)
      QubeWorkflows.client = fake_client
    end

    it "starts a branch with its body, the discriminator fixed and nils left out" do
      connection = Struct.new(:qube_id).new("conn-1")
      QubeWorkflows.add_transaction.invoice(connection, {customer_ref: {list_id: "80000001"}},
        references: {"customer" => "create"}, reference: "invoice-1", webhook_url: "https://app.test/runs")
      expect(fake_client.runs).to eq([{
        connection_id: "conn-1", workflow: "add_transaction", reference: "invoice-1",
        webhook_url: "https://app.test/runs", version: nil,
        input: {operation: "invoice.create", params: {customer_ref: {list_id: "80000001"}},
                references: {"customer" => "create"}}
      }])
    end

    it "builds a branch's input alone, and starts any input with start" do
      input = QubeWorkflows::AddTransaction.bill_input({vendor_ref: {full_name: "Acme"}}, adds: [])
      expect(input).to eq({operation: "bill.create", params: {vendor_ref: {full_name: "Acme"}}, adds: []})
      QubeWorkflows::AddTransaction.start("conn-2", input, reference: "bill-1", webhook_url: "https://app.test/runs", version: 3)
      expect(fake_client.runs.last).to include(connection_id: "conn-2", input: input, version: 3)
    end

    it "takes an input named after a Ruby keyword, and several bodies as keywords" do
      QubeWorkflows.upsert.customer("conn-1", add: {name: "Acme"}, update: {name: "Acme"}, class: "Wholesale",
        reference: "customer-1", webhook_url: "https://app.test/runs")
      expect(fake_client.runs.last[:input]).to eq({kind: "customer", add: {name: "Acme"}, class: "Wholesale", update: {name: "Acme"}})
      expect(QubeWorkflows::Upsert.future_list_input(add: {name: "Later"}, update: {})).to eq({kind: "future_list", add: {name: "Later"}, update: {}})
    end

    it "takes a workflow without branches' inputs as keywords" do
      QubeWorkflows.record_payment.start("conn-1", payment: {total_amount: "10.00"}, reference: "payment-1",
        webhook_url: "https://app.test/runs")
      expect(fake_client.runs.last[:input]).to eq({payment: {total_amount: "10.00"}})
      expect { QubeWorkflows::RecordPayment.input(txn_id: "1") }.to raise_error(ArgumentError, /payment/)
    end

    it "takes a client per call, and says how to set the default" do
      QubeWorkflows.client = nil
      expect { QubeWorkflows::Resolve.start("conn-1", kind: "customer", reference: "r", webhook_url: "https://app.test/runs") }
        .to raise_error(ArgumentError, /QubeWorkflows.client isn't set/)
      QubeWorkflows::Resolve.start("conn-1", kind: "customer", reference: "r", webhook_url: "https://app.test/runs", client: fake_client)
      expect(fake_client.runs.last[:input]).to eq({kind: "customer"})
    end
  end

  describe "names" do
    it "renames what would clash and reads Ruby keywords through the binding" do
      files = render(workflow({
        "type" => "object", "additionalProperties" => false, "required" => ["end"],
        "properties" => {
          "end" => {"$operation" => "customer.create"}, "version" => {"type" => "integer"},
          "type" => {"type" => "string"}, "self" => {"type" => "boolean"}
        },
        "discriminator" => {"propertyName" => "kind"},
        "oneOf" => [{"title" => "start", "properties" => {"kind" => {"const" => "a"}}}, {"title" => "name", "properties" => {"kind" => {"const" => "b"}}}]
      }, key: "class"))
      expect(files.ruby).to include("def self.class_\n    Class\n", "def self.start_(connection, end_, self: nil, type: nil, version_: nil, reference:",
        "def self.name__input(end_, self: nil, type: nil, version_: nil)",
        "{kind: \"b\", end: end_, self: binding.local_variable_get(:self), type: type, version: version_}.compact")
      load_ruby(files.ruby)
      expect(QubeWorkflows.class_::WORKFLOW).to eq("class")
      expect(QubeWorkflows::Class.start__input({name: "x"}, self: true, version_: 2)).to eq({kind: "a", end: {name: "x"}, self: true, version: 2})
      Dir.mktmpdir do |dir|
        File.write(File.join(dir, "qube_workflows.rbs"), files.rbs)
        output = IO.popen([RbConfig.ruby, Gem.bin_path("rbs", "rbs"), "-I", File.join(root, "sig"), "-I", dir, "validate"],
          err: [:child, :out], &:read)
        expect($?.success?).to be(true), output
      end
    end

    it "takes the body positionally in every branch or in none, by the workflow's body fields" do
      branches = [
        {"title" => "a", "properties" => {"kind" => {"const" => "a"}, "add" => {"$operation" => "customer.create"}}},
        {"title" => "b", "properties" => {"kind" => {"const" => "b"}, "add" => {"type" => "object"}}}
      ]
      input = {"type" => "object", "required" => ["kind", "add"], "discriminator" => {"propertyName" => "kind"},
               "properties" => {"kind" => {"type" => "string"}, "add" => {"type" => "object"}}, "oneOf" => branches}
      ruby = render(workflow(input)).ruby
      expect(ruby).to include("def self.a(connection, add, reference:", "def self.b(connection, add, reference:")

      branches[1]["properties"]["update"] = {"$operation" => "customer.update"}
      ruby = render(workflow(input)).ruby
      expect(ruby).to include("def self.a(connection, add:, reference:", "def self.b(connection, add:, update: nil, reference:")
    end

    it "types an operation it doesn't know as a Hash" do
      files = render(workflow({"type" => "object", "required" => ["body"], "properties" => {"body" => {"$operation" => "widget.create"}}}))
      expect(files.rbs).to include("body: Hash[untyped, untyped]")
      expect(files.ruby).to include("the widget.create body (an operation this version of qube_sync doesn't\n")
      expect(files.ruby).not_to include("@see")
    end

    it "refuses a name QuBe Sync doesn't allow, rather than writing it into code" do
      expect { render(workflow({"type" => "object", "properties" => {"a b" => {"type" => "string"}}})) }
        .to raise_error(described_class::Error, /isn't a name/)
      expect { render(workflow({"type" => "object"}, key: "x\nend")) }.to raise_error(described_class::Error)
      expect { render({"workflows" => {}}) }.to raise_error(described_class::Error, /not a workflow types document/)
    end
  end

  describe ".check" do
    let(:path) { "lib/qube_workflows.rb" }
    let(:existing) { render(document, drafts: true).ruby }

    def check(text = existing)
      described_class.check(text, client: fake_client, source: source, path: path)
    end

    it "is current on a 304, asking with the file's digest and drafts flag" do
      fake_client.answers << :not_modified
      result = check
      expect([result.status, result.exit_status]).to eq([:current, 0])
      expect(fake_client.calls).to eq([{include_drafts: true, etag: document["digest"]}])
    end

    it "is current when the served digest is the file's" do
      fake_client.answers << document
      expect(check.status).to eq(:current)
    end

    it "is stale when the digest differs, naming the workflows that changed" do
      changed = JSON.parse(JSON.generate(document))
      changed["digest"] = "sha256:#{"d" * 64}"
      changed["workflows"]["upsert"]["version"] = 3
      changed["workflows"].delete("record_payment")
      changed["workflows"]["ensure"] = changed["workflows"]["upsert"]
      fake_client.answers << changed
      result = check
      expect([result.status, result.exit_status]).to eq([:stale, 1])
      expect(result.changes).to eq(["ensure (new)", "record_payment (removed)", "upsert (changed)"])
      expect(result.message).to eq("#{path} is out of date (ensure (new), record_payment (removed), upsert (changed)): " \
        "run `qube_sync workflows --drafts` and commit the result")
    end

    it "warns and passes when QuBe Sync can't be reached or answers 5xx" do
      fake_client.answers << Errno::ECONNREFUSED << QubeSync::APIError.new(status: 503, body: "")
      2.times do
        result = check
        expect([result.status, result.exit_status]).to eq([:unreachable, 0])
        expect(result.message).to start_with("couldn't reach QuBe Sync")
      end
    end

    it "fails on a 401" do
      fake_client.answers << QubeSync::APIError.new(status: 401, body: '{"errors":"unauthorized"}')
      result = check
      expect([result.status, result.exit_status]).to eq([:error, 1])
      expect(result.message).to include("401")
    end

    it "fails on a file without a header" do
      expect(check("module QubeWorkflows; end\n").exit_status).to eq(1)
      expect(fake_client.calls).to eq([])
    end
  end

  describe QubeSync::WorkflowTypes::CLI do
    let(:out) { StringIO.new }
    let(:err) { StringIO.new }
    let(:made) { [] }

    def cli(env = {"QUBE_API_KEY" => "sk_test"})
      client = fake_client
      seen = made
      described_class.new(env: env, out: out, err: err, client_factory: lambda { |api_key:, base_url:|
        seen << [api_key, base_url]
        client
      })
    end

    around do |example|
      Dir.mktmpdir { |dir| Dir.chdir(dir) { example.run } }
    end

    it "writes both files, and --check passes on them" do
      fake_client.answers << document << :not_modified
      expect(cli.run(%w[workflows --drafts])).to eq(0)
      expect(File.read("lib/qube_workflows.rb")).to eq(QubeSync::WorkflowTypes.render(document, source: source, drafts: true).ruby)
      expect(File.read("sig/qube_workflows.rbs")).to include("module QubeWorkflows")
      expect(err.string).to include("warning: QuBe Sync's operations")
      expect(cli.run(%w[workflows --check])).to eq(0)
      expect(fake_client.calls.last).to eq({include_drafts: true, etag: document["digest"]})
      expect(out.string).to include("lib/qube_workflows.rb is up to date")
    end

    it "takes the paths, and QUBE_BASE_URL with or without /api/v2" do
      fake_client.answers << document
      expect(cli({"QUBE_API_KEY" => "sk_test", "QUBE_BASE_URL" => "https://qube.example/api/v2/"})
        .run(%w[workflows --output app/qube/qube_workflows.rb --sig sig/workflows.rbs])).to eq(0)
      expect(made).to eq([["sk_test", "https://qube.example"]])
      expect(File.exist?("app/qube/qube_workflows.rb") && File.exist?("sig/workflows.rbs")).to be(true)
    end

    it "fails --check on a stale file and a 401, and passes with a warning when QuBe Sync is down" do
      fake_client.answers << document
      cli.run(%w[workflows])
      fake_client.answers << document.merge("digest" => "sha256:#{"e" * 64}")
      expect(cli.run(%w[workflows --check])).to eq(1)
      expect(err.string).to include("is out of date")
      fake_client.answers << QubeSync::APIError.new(status: 401, body: "")
      expect(cli.run(%w[workflows --check])).to eq(1)
      fake_client.answers << Net::OpenTimeout
      expect(cli.run(%w[workflows --check])).to eq(0)
      expect(err.string).to include("warning: couldn't reach QuBe Sync")
    end

    it "needs QUBE_API_KEY, a file to check, and the workflows command" do
      expect(cli({}).run(%w[workflows])).to eq(1)
      expect(err.string).to include("QUBE_API_KEY")
      expect(cli.run(%w[workflows --check])).to eq(1)
      expect(err.string).to include("isn't there")
      expect(cli.run(%w[nope])).to eq(1)
      expect(cli.run(%w[--help])).to eq(0)
    end

    it "is the gem's executable" do
      exe = File.join(root, "exe/qube_sync")
      output = IO.popen([RbConfig.ruby, "-I", File.join(root, "lib"), exe, "workflows"], err: [:child, :out], &:read)
      expect($?.exitstatus).to eq(1)
      expect(output).to include("QUBE_API_KEY")
    end
  end
end
